import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';

export function generateClinicalPDF(data) {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header - "Vocalis AI" Branding
  doc.setFillColor(30, 41, 59); // Dark blue header
  doc.rect(0, 0, pageWidth, 40, 'F');
  
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(24);
  doc.text('VOCALIS AI', 15, 25);
  
  doc.setFontSize(10);
  doc.text('Advanced Vocal Biomarker Intelligence Report', 15, 33);
  
  doc.setFontSize(10);
  doc.text(`Report ID: ${data.reportId}`, pageWidth - 70, 20);
  doc.text(`Generated: ${new Date(data.generatedAt).toLocaleString()}`, pageWidth - 70, 27);

  // Patient Info Section
  doc.setTextColor(30, 41, 59);
  doc.setFontSize(16);
  doc.text('Patient Profile Summary', 15, 55);
  
  doc.setDrawColor(30, 41, 59);
  doc.setLineWidth(0.5);
  doc.line(15, 58, 80, 58);

  const statusColor = data.patientStatus === 'HIGH' ? [239, 68, 68] : [16, 185, 129];
  doc.setTextColor(0, 0, 0);
  doc.setFontSize(12);
  doc.text(`Patient ID: ${data.userId}`, 15, 68);
  doc.text('Clinical Status:', 15, 75);
  
  doc.setTextColor(statusColor[0], statusColor[1], statusColor[2]);
  doc.setFont(undefined, 'bold');
  doc.text(data.patientStatus, 48, 75);
  doc.setFont(undefined, 'normal');

  // Key Metrics Table
  doc.setTextColor(30, 41, 59);
  doc.setFontSize(14);
  doc.text('Biomarker Aggregates', 15, 90);

  const metrics = [
    ['Metric', 'Value', 'Status'],
    ['Avg Health Score', `${data.summaryMetrics.avgRiskScore || 0}%`, (data.summaryMetrics.avgRiskScore || 0) > 70 ? 'Concern' : 'Stable'],
    ['Submission Streak', `${data.summaryMetrics.streakDays || 0} Days`, 'Active'],
    ['Baseline Deviation', `${data.summaryMetrics.baselineDeviation || 0}%`, 'Calculated vs Day 1']
  ];

  doc.autoTable({
    startY: 95,
    head: [metrics[0]],
    body: metrics.slice(1),
    theme: 'striped',
    headStyles: { fillColor: [79, 70, 229] }
  });

  // Accessing the final Y position after table generation
  const finalY = doc.lastAutoTable?.finalY || 95;
  let nextY = finalY + 15;
  doc.setFontSize(14);
  doc.setTextColor(30, 41, 59);
  doc.text('Clinical Observations', 15, nextY);
  
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  const insightList = data.detailedInsights || ["No specific observations for this period."];
  let insightText = insightList.join('\n\n');
  let splitInsights = doc.splitTextToSize(insightText, pageWidth - 30);
  doc.text(splitInsights, 15, nextY + 8);

  // Recommendations
  nextY = nextY + (splitInsights.length * 6) + 20;
  if (nextY > 260) { doc.addPage(); nextY = 20; } // Basic page overflow check
  
  doc.setFillColor(248, 250, 252);
  doc.rect(10, nextY - 10, pageWidth - 20, 30, 'F');
  
  doc.setFontSize(12);
  doc.setTextColor(30, 41, 59);
  doc.setFont(undefined, 'bold');
  doc.text('Clinical Recommendation:', 15, nextY);
  
  doc.setFont(undefined, 'normal');
  doc.setTextColor(20, 20, 20);
  doc.text(data.recommendation, 15, nextY + 8);

  // Footer
  doc.setFontSize(8);
  doc.setTextColor(150, 150, 150);
  doc.text('This report is generated by Vocalis AI for screening assistance and should not replace professional medical diagnosis.', pageWidth / 2, doc.internal.pageSize.getHeight() - 10, { align: 'center' });

  doc.save(`Clinical_Report_${data.userId}.pdf`);
}
